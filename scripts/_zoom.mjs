import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:3001/');
await page.waitForTimeout(800);
await page.click('text=New Settlement');
await page.click('text=Found the Settlement');
await page.waitForTimeout(500);
await page.evaluate(() => { const { game, cl } = window; cl.playBot(game.state, 4, 5); });
await page.evaluate(() => { const { game } = window; game.setSpeed(0); document.querySelectorAll('.banner').forEach((e) => e.remove()); document.getElementById('ui').style.display='none';
  const s = game.state; const h = s.buildings.find(b=>b.type==='townhall'); game.renderer.cam.zoom = 2.6; game.renderer.centerOn(h.x+1.5, h.y+1.5); });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-a.png` });
await page.evaluate(() => { const { game } = window; const s = game.state; const h = s.buildings.filter(b=>b.type==='house'); const b=h[Math.floor(h.length/2)]; game.renderer.centerOn(b.x+1, b.y+1); });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}-b.png` });
console.log('errors', errors);
await browser.close();
